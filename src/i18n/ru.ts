/** Prepositional case ("в 1 операции" vs "в 2/5 операциях") only distinguishes singular from everything else. */
function pluralizeTransactions(count: number): string {
  const isSingular = count % 10 === 1 && count % 100 !== 11;
  return isSingular ? "операции" : "операциях";
}
